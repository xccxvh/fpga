#ifndef PROTOCOL_FROZEN_H
#define PROTOCOL_FROZEN_H

#include <stdint.h>

/*
 * 已冻结的协议常量 —— 联合工程的协议兼容层。
 *
 * ┌─ 为什么需要这一层 ────────────────────────────────────────────────┐
 * │ 团队已冻结两项协议：                                                │
 * │   DISPLAY_FORMAT 的 RGB565 枚举值 = 1                               │
 * │   BitBlt  RGB565 VERSION = 0x00020000（V2.0）                       │
 * │   Display RGB565 VERSION = 0x00030000（V3.0）                       │
 * │                                                                     │
 * │ 但 B 组的权威头文件（bitblt_regs.h / display_regs.h）目前【尚未     │
 * │ 同步】—— 里面还是 V0_4 = 0x00010004，FORMAT 表里只有 XRGB8888 = 0。 │
 * │                                                                     │
 * │ 本工程的原则是"不复制 B 的权威定义"，所以下面是【暂时】代持，        │
 * │ 并且全工程只有这一处代持，不允许在调用点再抄一遍数字。              │
 * │                                                                     │
 * │ 检测"B 有没有同步"由 tests/test_contract.c 负责：它可以直接 include │
 * │ B 的头文件（库代码不行 —— 那会破坏 check-hw-isolation，而且寄存器   │
 * │ 头文件里的 RV32 指针转换在宿主机上编不过）。B 一同步，那边会编译     │
 * │ 失败并提示把下面这几行改成直接引用 B 的宏。**不会长期并存两套定义。**│
 * └─────────────────────────────────────────────────────────────────────┘
 *
 * 版本编码规则（团队约定）：
 *   高 16 位 = 主版本，低 16 位 = 次版本。
 *   例：0x00020000 = V2.0，0x00030001 = V3.1。
 *   RGB565 属于不兼容升级，所以 BitBlt 进 V2.0、Display 进 V3.0。
 *
 * 仍未冻结的项（UDP 完成通知的寄存器/中断/ACK）在 protocol_unfrozen.h，
 * 两者刻意分开：这个文件里的值可以直接用，那里的必须先查能力。
 */

/*
 * 注意数值巧合：B 现有的 DISPLAY_VERSION_V0_2 同样是 0x00020000，
 * 但那是【显示控制器 V0.2 的旧版本号】，与这里的 BITBLT_VERSION_RGB565
 * 只是数值相同，属于两个不同的寄存器。grep 0x00020000 会同时命中，
 * 看上下文区分。
 */


/* ------------------------------------------------------------------ */
/* 版本号拆分                                                          */
/* ------------------------------------------------------------------ */

#define PROTO_VERSION_MAJOR(v) ((uint32_t)((uint32_t)(v) >> 16))
#define PROTO_VERSION_MINOR(v) ((uint32_t)((uint32_t)(v) & 0xFFFFu))


/* ------------------------------------------------------------------ */
/* DISPLAY_FORMAT 枚举                                                 */
/* ------------------------------------------------------------------ */

/*
 * XRGB8888 = 0 是历史兼容枚举，仍然有效，但它【不是】当前联合工程的
 * 默认格式 —— 当前默认是 RGB565。保留它只是为了还能识别已板测的
 * XRGB8888 位流（比如 V0.4 的 1080p 那版）。
 */
#define PROTO_DISPLAY_FORMAT_XRGB8888 0u

/* B 同步后改成 DISPLAY_FORMAT_RGB565 */
#define PROTO_DISPLAY_FORMAT_RGB565   1u


/* ------------------------------------------------------------------ */
/* 版本                                                                */
/* ------------------------------------------------------------------ */

/* B 同步后改成 BITBLT_VERSION_RGB565 */
#define PROTO_BITBLT_VERSION_RGB565   0x00020000u

/* B 同步后改成 DISPLAY_VERSION_RGB565 */
#define PROTO_DISPLAY_VERSION_RGB565  0x00030000u


/* ------------------------------------------------------------------ */
/* 查询                                                                */
/* ------------------------------------------------------------------ */

/*
 * 当前联合工程默认的显示格式。
 *
 * 值一定是一个可用的枚举（当前为 RGB565 = 1）—— 协议冻结之后，
 * "未知"不再是一个合法结论。
 */
uint32_t proto_display_format_default(void);

/*
 * 检查一个版本号是否与当前联合工程匹配。
 *
 * 比对的是【完整 32 位】而不是只比主版本：主版本相同、次版本不同的
 * 位流仍可能是未验证的组合，宁可 fail-fast 让人去查，也不要带着
 * 不确定的次版本继续跑。
 */
int proto_display_version_compatible(uint32_t version);
int proto_bitblt_version_compatible(uint32_t version);

#endif
